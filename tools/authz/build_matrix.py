"""Seed / refresh tests/authz/matrix.yaml from the OpenAPI specs (TEST_STRATEGY §5).

    python tools/authz/build_matrix.py [--specs docs/api] [--out tests/authz/matrix.yaml]

Existing rows are kept as they are (they may have been reviewed by hand). New operations
get roles inferred from the summary hint, e.g. "(staff, admin)"; anything that can't be
inferred is written with `review: true` so check_matrix.py fails until someone decides.
Inventory is staff/admin only (API README §3); `security: []` means public.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve()
V2 = HERE.parents[2]  # repository root
DEFAULT_SPECS = V2 / "docs" / "api"
DEFAULT_OUT = V2 / "tests" / "authz" / "matrix.yaml"

METHODS = ("get", "post", "put", "patch", "delete")
SERVICE_BASES = {
    "identity": "/api/identity/v1",
    "catalog": "/api/catalog/v1",
    "inventory": "/api/inventory/v1",
    "orders": "/api/orders/v1",
    "documents": "/api/documents/v1",
}
ROLE_ORDER = ["anonymous", "user", "staff", "admin", "service"]
OWNERSHIP = {"public", "self", "same_org", "requester", "staff", "admin", "service", "any"}


def infer(service: str, path: str, op: dict[str, Any]) -> dict[str, Any]:
    summary = str(op.get("summary", ""))
    hint_match = re.search(r"\(([^)]*)\)\s*(?:-|$|→)", summary) or re.search(r"\(([^)]*)\)", summary)
    hint = hint_match.group(1).lower() if hint_match else ""
    row: dict[str, Any] = {}

    if op.get("security") == []:
        row.update(roles=["anonymous", "user", "staff", "admin"], ownership="public")
    elif path.startswith("/internal/") or "service token" in hint:
        row.update(roles=["service"], ownership="service")
    elif service == "inventory":
        row.update(roles=["staff", "admin"], ownership="staff")
    elif hint.startswith("admin") and "staff" not in hint.split(";")[0]:
        row.update(roles=["admin"], ownership="admin")
    elif hint.startswith(("staff, admin", "staff;", "staff)")) or hint == "staff" or hint.startswith("staff read"):
        row.update(roles=["staff", "admin"], ownership="staff")
    elif hint.startswith("requester or admin"):
        row.update(roles=["user", "admin"], ownership="requester")
    elif hint.startswith("requester, staff or admin"):
        row.update(roles=["user", "staff", "admin"], ownership="requester")
    elif hint == "public":
        row.update(roles=["anonymous", "user", "staff", "admin"], ownership="public")
    elif path.startswith(("/me", "/cart")):
        row.update(roles=["user", "staff", "admin"] if path.startswith("/me") else ["user"], ownership="self")
    else:
        row.update(roles=["user", "staff", "admin"], ownership="any", review=True)

    if path.startswith("/cart") or (service == "orders" and path == "/requests" and op.get("_method") == "post"):
        row["cimh_forbidden"] = True
    if hint and hint not in ("public",):
        row["note"] = hint
    return row


def operations(specs: Path) -> list[tuple[str, str, str, dict[str, Any]]]:
    out = []
    for service, _base in SERVICE_BASES.items():
        spec_file = specs / f"{service}.openapi.yaml"
        if not spec_file.exists():
            continue
        spec = yaml.safe_load(spec_file.read_text(encoding="utf-8"))
        for path, item in (spec.get("paths") or {}).items():
            for method in METHODS:
                if method in item:
                    op = dict(item[method])
                    op["_method"] = method
                    out.append((service, method.upper(), path, op))
    return out


def key(service: str, method: str, path: str) -> str:
    return f"{method} {SERVICE_BASES[service]}{path}"


def build(specs: Path, existing: dict[str, Any]) -> dict[str, Any]:
    rows = dict(existing.get("endpoints") or {})
    for service, method, path, op in operations(specs):
        k = key(service, method, path)
        if k not in rows:
            rows[k] = infer(service, path, op)
    return {
        "version": 1,
        "roles": ROLE_ORDER,
        "ownership_values": sorted(OWNERSHIP),
        "endpoints": dict(sorted(rows.items(), key=lambda kv: (kv[0].split(" ", 1)[1], kv[0]))),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--specs", type=Path, default=DEFAULT_SPECS)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    existing = yaml.safe_load(args.out.read_text(encoding="utf-8")) if args.out.exists() else {}
    matrix = build(args.specs, existing or {})
    args.out.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by tools/authz/build_matrix.py, then reviewed by hand. Rows are never overwritten.\n"
    args.out.write_text(header + yaml.safe_dump(matrix, sort_keys=False, width=200), encoding="utf-8")
    n = len(matrix["endpoints"])
    review = sum(1 for r in matrix["endpoints"].values() if r.get("review"))
    print(f"{n} endpoints, {review} need review -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
